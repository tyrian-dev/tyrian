#!/usr/bin/env bash
# Build a self-contained copy of the production contracts for static analysis.
#
# Why: `contracts/foundry.toml` uses `libs = ["../node_modules", "node_modules"]`
# and remappings that point outside the project root. Foundry then reports the
# same dependency file twice (once as `../node_modules/...`, once as an absolute
# path). Slither/Aderyn/Solar treat the build-info as one source graph and abort
# with "identifier already declared" / "content not found".
#
# This script copies `contracts/src` plus the exact dependency folders into a
# temporary project where dependencies live inside the root, so every tool sees a
# single canonical path per file. The contracts are copied verbatim; nothing is
# rewritten and no mock is removed.
#
# Usage: bash scripts/static-analysis-scope.sh <destination-directory>
set -euo pipefail

DEST="${1:-}"
if [ -z "$DEST" ]; then
    echo "usage: bash scripts/static-analysis-scope.sh <destination-directory>" >&2
    exit 2
fi

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONTRACTS="$REPO_ROOT/contracts"
NODE_MODULES="$REPO_ROOT/node_modules"

if [ ! -d "$CONTRACTS/src" ]; then
    echo "error: $CONTRACTS/src not found" >&2
    exit 1
fi
if [ ! -d "$NODE_MODULES/@openzeppelin/contracts" ]; then
    echo "error: @openzeppelin/contracts missing under $NODE_MODULES (run bun install)" >&2
    exit 1
fi

rm -rf "$DEST"
mkdir -p "$DEST/node_modules/@openzeppelin"
cp -R "$CONTRACTS/src" "$DEST/src"
cp -R "$NODE_MODULES/@openzeppelin/contracts" "$DEST/node_modules/@openzeppelin/contracts"

cat > "$DEST/foundry.toml" <<'TOML'
# Generated by scripts/static-analysis-scope.sh. Do not edit by hand.
[profile.default]
src = "src"
out = "out"
libs = ["node_modules"]
solc_version = "0.8.26"
optimizer = true
optimizer_runs = 200

remappings = ["@openzeppelin/contracts/=node_modules/@openzeppelin/contracts/"]
TOML

printf 'scope: %s\n' "$DEST"
